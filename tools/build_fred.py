#!/usr/bin/env python3
"""Bundle Fred's native modules for standalone/file:// use, without npm."""
from pathlib import Path
import argparse,re

root=Path(__file__).resolve().parents[1]/'fred';parts=[]
for name in ('engine.mjs','screen.mjs','sound.mjs','audio.mjs','app.mjs'):
    source=(root/name).read_text();source=re.sub(r'^import .*?;\n','',source,flags=re.M)
    source=re.sub(r'^export (?=(?:class|function|const)\b)','',source,flags=re.M);parts.append('// '+name+'\n'+source)
bundle='// Generated by tools/build_fred.py. Native JavaScript only.\n(()=>{\n'+'\n'.join(parts)+'\n})();\n'
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args();target=root/'game.js'
if args.check:
    if not target.exists() or target.read_text()!=bundle:raise SystemExit('Fred bundle is stale; run python3 tools/build_fred.py')
    print('Fred native bundle is current.')
else:target.write_text(bundle);print('Built fred/game.js')
