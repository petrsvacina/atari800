#!/usr/bin/env python3
"""Karateka ATR research exporter. Original CPU is an OFFLINE oracle only.

Consumes a 64K loaded Atari800 RAM dump, exports only named animation tables.
No executable original bytes are written to the web game.
"""
import argparse,hashlib,json,sys,random
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SOURCE_SHA256='4db2200ce3fbefa109f337fe835fc0fbd7efd1144f598e14aafffb62e256d675'
TABLES={'legSequence':(0x6300,256),'armSequence':(0x63be,60),'stride':(0x6360,160),
 'stance':(0x70c6,42),'reach':(0x7300,26),'contactClass':(0x731a,26),
 'highContact':(0x7334,10),'middleContact':(0x733e,10),'closeContact':(0x7348,10),
 'lowContact':(0x7352,10),'edgeContact':(0x735c,10),'specialReach':(0x7446,10),
 'specialOffset':(0x7450,11),'aiThresholds':(0xbfe1,31),'guardKick':(0xbbd9,6),'guardPunch':(0xbbdf,6),'guardWait':(0xbbe5,6)}
def load(path):
 if hashlib.sha256((ROOT/'Karateka.atr').read_bytes()).hexdigest()!=SOURCE_SHA256:raise ValueError('Unsupported source ATR')
 memory=path.read_bytes()
 if len(memory)!=65536 or memory[0x6400:0x6404]!=bytes.fromhex('a9ff852b'):raise ValueError('Expected loaded supplied Karateka disk')
 return memory

def export(memory):
 data={name:list(memory[start:start+count]) for name,(start,count) in TABLES.items()}
 data['sourceSha256']=SOURCE_SHA256
 target=ROOT/'karateka/assets/motion.js';target.write_text('// Generated by tools/karateka_extract.py; data only.\nglobalThis.KARATEKA_MOTION_DATA='+json.dumps(data,separators=(',',':'))+';\n')
 return data

def oracle(memory,folder):
 from py65.devices.mpu6502 import MPU
 def call(address,values,command=0):
  m=list(memory);m[0x20:0x30]=values[:16]
  for key,value in values[16].items():m[int(key)]=value
  cpu=MPU(memory=m);cpu.pc=address;cpu.a=command;cpu.sp=0xfd;m[0x1fe]=0xfe;m[0x1ff]=0xff
  for _ in range(10000):
   if cpu.pc==0xffff:break
   cpu.step()
  else:return None
  return [m[0x20:0x30],{str(a):m[a] for a in (0x45,0x46,0x47)}]
 rng=random.Random(0x1984);cases=[]
 # All animation indices, heights, directions and commands, sampled independently.
 # Side effects (input latch, footstep/contact) are part of each expected state.
 for i in range(16000):
  f=[rng.randrange(38),rng.randrange(38),rng.randrange(5,36),0,rng.randrange(7),rng.randrange(74),rng.randrange(54),rng.choice((0,1,255)),rng.choice((0,1)),rng.choice((0,1,255)),rng.choice((0,1,255)),255,rng.choice((1,255)),0,0,rng.choice((0,255))]
  address=0x6540 if i%2 else 0x6400;command=rng.choice((0,0x9b,0xd1,0xd7,0xc2,0xc5,0xc6));g={str(a):v for a,v in ((0x33,rng.randrange(20)),(0x45,0),(0x46,0),(0x47,0),(0x50,rng.randrange(2)),(0x62,rng.randrange(5,36)))}
  result=call(address,f+[g],command)
  if result:cases.append({'routine':address,'command':command,'fighter':f,'globals':g,'expected':result})
 folder.mkdir(parents=True,exist_ok=True);(folder/'motion-oracle.json').write_text(json.dumps(cases,separators=(',',':'))+'\n');print('Exported',len(cases),'original-routine motion cases')
if __name__=='__main__':
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--memory',type=Path,required=True);p.add_argument('--oracle',type=Path);a=p.parse_args();m=load(a.memory);export(m)
 if a.oracle:oracle(m,a.oracle)
