#!/usr/bin/env python3
"""Build the native bilingual adventure and its original bitmap assets."""
import base64
import hashlib
import json
from pathlib import Path
import re
import shutil
from extract_assets import png
from neverstory2_extract import ROOT, SOURCE_DIR, SOURCES, files
from neverstory2_program import english, czech


def build():
    target=ROOT/'neverending-story-2'; assets=target/'assets'; assets.mkdir(parents=True,exist_ok=True)
    research=ROOT/'research/neverending-story-2'; research.mkdir(parents=True,exist_ok=True)
    languages={}; provenance={}
    for lang in ('cs','en'):
        source=files(lang); programs=[]
        for part in (0,1,2):
            program=english(part) if lang=='en' else czech(part)[0]
            program['inputs']=[i for i,op in enumerate(program['ops']) if op[0]=='input']
            program['pauses']=[i for i,op in enumerate(program['ops']) if op[0]=='pause']
            if part:
                last=max(program['inputs'])
                ending=next(i for i,op in enumerate(program['ops']) if i>last and op[0]=='image')
                program['rooms']['13']=ending
            programs.append(program)
        languages[lang]={'programs':programs,'font':base64.b64encode(source['NICE.FNT']).decode(),
                         'pictures':{n:base64.b64encode(b).decode() for n,b in source.items() if n.endswith('.MIC') and len(b)==3200}}
        provenance[lang]={'source':SOURCES[lang][0],'sha256':SOURCES[lang][1],
                          'files':{n:{'bytes':len(b),'sha256':hashlib.sha256(b).hexdigest()} for n,b in source.items()},
                          'programOperations':[len(p['ops']) for p in programs]}
    palette=list((ROOT/'research/neverending-story/default.act').read_bytes())
    payload={'languages':languages,'palette':palette}
    (assets/'data.js').write_text('// Original adventure predicates, text, font and bitmaps; no CPU or BASIC runtime.\n'
        'globalThis.NEVERENDING2_DATA='+json.dumps(payload,separators=(',',':'),ensure_ascii=True)+';\n')
    picture=files('en')['TITLESCR.MIC']; colors=[picture[7680],0,254,picture[7683]]; rgba=bytearray()
    for b in picture[:7680]:
        for shift in (6,4,2,0):
            c=(colors[(b>>shift)&3]&254)*3;rgba.extend((bytes(palette[c:c+3])+b'\xff')*2)
    png(assets/'loading.png',320,192,rgba)
    shutil.copyfile(assets/'loading.png',ROOT/'portal/assets/neverending-story-2.png')
    shutil.copyfile(SOURCE_DIR/'MANUAL.pdf',assets/'manual-cs.pdf')
    shutil.copyfile(SOURCE_DIR/'Neverending story ENG manual.jpg',assets/'manual-en.jpg')
    provenance['manuals']={n:hashlib.sha256((assets/n).read_bytes()).hexdigest() for n in ('manual-cs.pdf','manual-en.jpg')}
    (research/'sources.json').write_text(json.dumps(provenance,indent=2)+'\n')
    pieces=[]
    for name in ('engine.mjs','screen.mjs','audio.mjs','app.mjs'):
        p=target/name
        if not p.exists(): continue
        text=p.read_text();text=re.sub(r'^import .*?;\n','',text,flags=re.M);text=re.sub(r'^export ','',text,flags=re.M)
        pieces.append('// '+name+'\n'+text)
    (target/'game.js').write_text('// Generated by tools/build_neverstory2.py.\n(()=>{\n\'use strict\';\n'+'\n'.join(pieces)+'\n})();\n')
    print('Built both original language programs, 26 locations, fonts, original pictures and manuals.')


if __name__=='__main__':build()
