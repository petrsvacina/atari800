#!/usr/bin/env python3
"""Bundle native JS and data for local file:// use, without a package manager."""
import argparse,json,re
from pathlib import Path
root=Path(__file__).resolve().parents[1]/'rescue-on-fractalus'
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
imports=re.compile(r'^import\s*(.*?)\s*from\s*[\'\"]\./([^\'\"]+)[\'\"];\s*$',re.M)
ordered=[];visited=set();visiting=set();sources={};exports={}
def visit(name):
    if name in visited:return
    if name in visiting:raise ValueError(f'Unexpected module cycle: {name}')
    visiting.add(name);source=(root/name).read_text();sources[name]=source
    for _,dependency in imports.findall(source):visit(dependency)
    exports[name]=re.findall(r'^export\s+(?:async\s+)?(?:function\*?\s+|class\s+|const\s+)(\w+)',source,re.M)
    # The two multiple const declarations also export their second value.
    for value in ['COCKPIT_HEIGHT','NTSC_HZ']:
        if re.search(r'^export const .*[,;]'+value+r'=',source,re.M):exports[name].append(value)
    ordered.append(name);visiting.remove(name);visited.add(name)
visit('app.mjs')
parts=['// Generated by tools/build_fractalus.py. Native JavaScript; no original CPU program.','(async()=>{','const __base=new URL("./",document.currentScript.src),__modules=Object.create(null);']
assets={path.stem:json.loads(path.read_text()) for path in sorted((root/'assets').glob('*.json'))}
parts.append('globalThis.FRACTALUS_ASSETS='+json.dumps(assets,separators=(',',':'))+';')
for name in ordered:
    source=sources[name]
    def replace(match):
        binding,dependency=match.groups()
        if binding.startswith('* as '):return 'const '+binding[5:]+'=__modules['+json.dumps(dependency)+'];'
        binding=re.sub(r'\bas\b',':',binding)
        for imported in re.findall(r'(\w+)\s*(?=[:,}])',binding):
            if imported not in exports[dependency]:raise ValueError(f'Missing export {dependency}:{imported}')
        return 'const '+binding+'=__modules['+json.dumps(dependency)+'];'
    source=imports.sub(replace,source)
    source=re.sub(r'^export\s+','',source,flags=re.M).replace('import.meta.url','__base')
    async_prefix='async ' if name=='app.mjs' else ''
    parts.append('// '+name+'\n__modules['+json.dumps(name)+']=await ('+async_prefix+'()=>{\n'+source+'\nreturn {'+','.join(exports[name])+'};\n})();')
parts.append('})().catch(error=>{console.error(error);const node=document.getElementById("error");if(node){node.hidden=false;node.textContent=error.message;}});\n')
bundle='\n'.join(parts);target=root/'game.js'
if args.check:
    if not target.exists() or target.read_text()!=bundle:raise SystemExit('Fractalus bundle is stale; run python3 tools/build_fractalus.py')
    print('Fractalus native standalone bundle is current.')
else:target.write_text(bundle);print(f'Built rescue-on-fractalus/game.js ({len(bundle.encode())} bytes)')
