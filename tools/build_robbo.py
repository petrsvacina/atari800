#!/usr/bin/env python3
"""Bundle native Robbo modules/data for direct file:// and static HTTP use."""
import argparse,json,re
from pathlib import Path
root=Path(__file__).resolve().parents[1]/'robbo'
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
imports=re.compile(r'^import\s*(.*?)\s*from\s*[\'\"]\./([^\'\"]+)[\'\"];\s*$',re.M)
reexports=re.compile(r'^export\s*\{(.*?)\}\s*from\s*[\'\"]\./([^\'\"]+)[\'\"];\s*$',re.M)
ordered=[];visited=set();sources={};exports={}
def visit(name):
    if name in visited:return
    visited.add(name);source=(root/name).read_text()
    extra=[]
    def reexport(match):
        binding,dependency=match.groups();extra.extend(v.strip().split(' as ')[-1] for v in binding.split(','))
        return 'import {'+binding+"} from './"+dependency+"';\n"
    source=reexports.sub(reexport,source);sources[name]=source
    for _,dependency in imports.findall(source):visit(dependency)
    exports[name]=re.findall(r'^export\s+(?:async\s+)?(?:function\*?\s+|class\s+|const\s+)(\w+)',source,re.M)+extra
    ordered.append(name)
visit('app.mjs')
parts=['// Generated by tools/build_robbo.py. Native JavaScript; no runtime CPU.', '(async()=>{', 'const __base=new URL("./",document.currentScript.src),__modules=Object.create(null);']
media={path.stem:json.loads(path.read_text()) for path in sorted((root/'assets').glob('*.json'))}
parts.append('globalThis.ROBBO_MEDIA='+json.dumps(media,separators=(',',':'))+';')
for name in ordered:
    def replace(match):
        binding,dependency=match.groups()
        if binding.startswith('* as '):return 'const '+binding[5:]+'=__modules['+json.dumps(dependency)+'];'
        binding=re.sub(r'\bas\b',':',binding)
        return 'const '+binding+'=__modules['+json.dumps(dependency)+'];'
    source=imports.sub(replace,sources[name]);source=re.sub(r'^export\s+','',source,flags=re.M).replace('import.meta.url','__base')
    parts.append('// '+name+'\n__modules['+json.dumps(name)+']=await ('+('async ' if name=='app.mjs' else '')+'()=>{\n'+source+'\nreturn {'+','.join(exports[name])+'};\n})();')
parts.append('})().catch(error=>{console.error(error);const node=document.getElementById("error");if(node){node.hidden=false;node.textContent=error.message;}});\n')
bundle='\n'.join(parts);target=root/'game.js'
if args.check:
    if not target.exists() or target.read_text()!=bundle:raise SystemExit('Robbo bundle is stale; run python3 tools/build_robbo.py')
    print('Robbo native standalone bundle is current.')
else:target.write_text(bundle);print(f'Built robbo/game.js ({len(bundle.encode())} bytes)')
