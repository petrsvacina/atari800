#!/usr/bin/env python3
"""Make a dependency-free classic script, also usable by opening index.html locally."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
pieces = []
for name in ['engine.mjs', 'screen.mjs', 'audio.mjs', 'app.mjs']:
    text = (ROOT / 'neverending-story' / name).read_text()
    text = re.sub(r'^import .*?;\n', '', text, flags=re.M)
    text = re.sub(r'^export ', '', text, flags=re.M)
    pieces.append('// ' + name + '\n' + text)
(ROOT / 'neverending-story/game.js').write_text('// Generated by tools/build_neverstory.py.\n(() => {\n\'use strict\';\n' + '\n'.join(pieces) + '\n})();\n')
print('Built neverending-story/game.js')
