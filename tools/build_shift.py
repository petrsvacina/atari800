#!/usr/bin/env python3
"""Bundle the standalone native Shift modules without a package manager."""
from pathlib import Path
import re

root=Path(__file__).resolve().parents[1]/'shift'
parts=[]
for name in ('engine.mjs','screen.mjs','audio.mjs','app.mjs'):
    source=(root/name).read_text()
    source=re.sub(r'^import .*?;\n','',source,flags=re.M)
    source=re.sub(r'^export (?=(?:class|function|const)\b)','',source,flags=re.M)
    parts.append('// '+name+'\n'+source)
(root/'game.js').write_text('// Generated by tools/build_shift.py. Native JavaScript only.\n(()=>{\n'+ '\n'.join(parts)+'\n})();\n')
print('Built shift/game.js')
