#!/usr/bin/env python3
"""Generate standalone game translation bundles from shared source/catalogues."""
import argparse,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def bundles():
 catalog=json.loads((ROOT/'localization/games.en.json').read_text())
 core=(ROOT/'localization/game-i18n.js').read_text()
 for game in json.loads((ROOT/'portal/games.json').read_text()):
  messages={**catalog['common'],**catalog['games'][game['id']]}
  if any(not isinstance(value,str) or not value for value in messages.values()):raise ValueError(game['id'])
  for source,target in messages.items():
   if source!=' '.join(source.split()):raise ValueError('Unnormalised translation key: '+source)
   if set(re.findall(r'\{\w+\}',source))!=set(re.findall(r'\{\w+\}',target)):raise ValueError('Translation placeholders differ: '+source)
  data=json.dumps(messages,ensure_ascii=False,separators=(',',':'))
  yield ROOT/game['source']/'i18n.js','// Generated by tools/build_game_i18n.py; edit localization/ sources.\n'+'globalThis.ATARI_GAME_MESSAGES = '+data+';\n'+core
def build(check=False):
 count=0
 for path,content in bundles():
  if check:
   if not path.is_file() or path.read_text()!=content:raise ValueError('Run python3 tools/build_game_i18n.py: '+str(path))
  else:path.write_text(content)
  count+=1
 print(('Verified' if check else 'Generated'),count,'standalone game translation bundles.')
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');build(p.parse_args().check)
